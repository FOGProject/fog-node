/**
 * UI smoke test.
 *
 * It lifts fog-node with the development asset build (grunt on), logs in
 * through the login page, and drives a real browser (Playwright Chromium)
 * through the main pages. A page fails when it throws a JavaScript error, logs
 * a console error, gets an HTTP error for any request, or does not render.
 *
 * Why: `npm test` lifts Sails with grunt off and never loads a page in a
 * browser. Dependabot PR #110 broke every page ("Scroller requires DataTables
 * 3.1 or greater") and still passed all the unit tests. This script fails on
 * that class of break.
 *
 * Usage: npm run test:ui          (development build)
 *        npm run test:ui:prod     (production build, as `npm start` runs it)
 *   It needs MongoDB, Redis, and the config that `npm run setup:dev` writes.
 *   It needs the browser once: npx playwright install chromium
 *
 * It lifts on port 1339, so it runs beside a dev server (1337) and the mocha
 * suite (1338). It writes a screenshot of each failed check to ui-smoke-out/.
 *
 * Check files: after the round trips, it runs every tools/smoke/checks/*.js,
 * in file-name order. Add a check there; do not edit this file. A check file
 * exports {name, run}. `run(ctx)` is async and throws when the check fails. A
 * check also fails on a console error or an HTTP status of 400 or more on
 * `ctx.page`, as the page checks do. All checks share `ctx.page`, so a check
 * opens the page it needs first and never relies on where the last one left
 * it. `ctx` holds:
 *   page       the signed-in page
 *   browser    the Playwright browser, to open other contexts (signed out, a
 *              dark color scheme). Close what you open; errors there are yours
 *              to check.
 *   base       the base URL, for example http://127.0.0.1:1339
 *   checkPage  checkPage(page, {path, table}), the page check below
 *   login      login(page) signs a page in as Administrator, as this run does
 *   PAGES      the page list below (a check file cannot require this file:
 *              main() runs when it loads)
 *   created    {host, storageGroup}: the names the round trips created; a
 *              name is undefined when its round trip failed
 *
 * Database: the run never uses the configured database. It empties the
 * database `<configured name>_test` (tools/lib/test-db.js), seeds the
 * Administrator account there with a password that exists only in memory
 * (the same seed as `npm run setup:dev`), and lifts on it. Redis sessions are
 * shared with a dev server, but session ids are random, so they do not collide.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const {chromium} = require('playwright');
const server = require('./lib/server');
const testDb = require('../lib/test-db');
const schema = require('../setup/lib/schema');

const root = server.root;
const port = 1339;
const base = `http://127.0.0.1:${port}`;
// A new password for each run. It only ever guards the test database.
const password = crypto.randomBytes(12).toString('hex');
// --prod lifts with the production asset build: concatenated and minified
// bundles (issue #115 broke that build, and nothing noticed).
const prod = process.argv.includes('--prod');
const outDir = path.join(root, 'ui-smoke-out');

// Every page in config/routes.js that renders the layout, except the edit
// pages, which need a record id (checkRoundTrip opens them). The sidebar hides
// a link whose page has no route yet, for example /hosts/pendingMacs
// (checks/ui16-04-sidebar.js). The list pages load their rows over AJAX into
// DataTables, so `table: true` also waits for DataTables to initialize.
const PAGES = [
  {path: '/'},
  {path: '/search?q=ui-smoke'},
  {path: '/account'},
  {path: '/hwinfo'},
  {path: '/hosts', table: true},
  {path: '/hosts/pending', table: true},
  {path: '/hosts/pendingAgents', table: true},
  {path: '/hosts/agentTokens', table: true},
  {path: '/groups', table: true},
  {path: '/images', table: true},
  {path: '/storagegroups', table: true},
  {path: '/storagenodes', table: true},
  {path: '/pxemenus', table: true},
  {path: '/roles', table: true},
  {path: '/tasks', table: true},
  {path: '/users', table: true},
  {path: '/workflows', table: true},
  {path: '/hosts/create'},
  {path: '/groups/create'},
  {path: '/images/create'},
  {path: '/storagegroups/create'},
  {path: '/storagenodes/create'},
  {path: '/pxemenus/create'},
  {path: '/users/create'}
];

const serverLog = [];

// Records every error that the page reports while `fn` runs.
async function collectErrors(page, fn) {
  const errors = [];
  const onConsole = (m) => { if (m.type() === 'error') errors.push(`console: ${m.text()}`); };
  const onPageError = (e) => errors.push(`exception: ${e.message}`);
  const onResponse = (r) => { if (r.status() >= 400) errors.push(`HTTP ${r.status()}: ${r.url()}`); };
  // net::ERR_ABORTED is the browser cancelling a request: when the check
  // navigates with a table-state save or a datatable reload still in flight,
  // or when page code drops a superseded request. Neither is a page fault. A
  // server fault shows as an HTTP status above, a script fault as a pageerror,
  // and a page that needs the cancelled request must fail the check's own
  // assertions. Every other network failure still counts.
  const onFailed = (r) => {
    const err = r.failure() && r.failure().errorText;
    if (err !== 'net::ERR_ABORTED') errors.push(`request failed: ${r.method()} ${r.url()} (${err})`);
  };
  page.on('console', onConsole);
  page.on('pageerror', onPageError);
  page.on('response', onResponse);
  page.on('requestfailed', onFailed);
  try {
    await fn();
  } catch (e) {
    errors.push(`check: ${e.message.split('\n')[0]}`);
  } finally {
    page.off('console', onConsole);
    page.off('pageerror', onPageError);
    page.off('response', onResponse);
    page.off('requestfailed', onFailed);
  }
  return errors;
}

async function login(page) {
  await page.goto(`${base}/login`, {waitUntil: 'networkidle'});
  await page.fill('input[name="username"]', 'Administrator');
  await page.fill('input[name="password"]', password);
  await Promise.all([page.waitForNavigation({waitUntil: 'networkidle'}), page.click('button[type="submit"]')]);
  if (new URL(page.url()).pathname === '/login') throw new Error('login failed: the page stayed on /login');
}

async function checkPage(page, spec) {
  await page.goto(base + spec.path, {waitUntil: 'networkidle'});
  if (new URL(page.url()).pathname === '/login') throw new Error('redirected to /login');
  await page.locator('.app-sidebar').waitFor({state: 'visible', timeout: 5000});
  await page.locator('.app-main').waitFor({state: 'visible', timeout: 5000});
  if (spec.table) {
    await page.waitForFunction(() => window.jQuery && jQuery.fn.dataTable && jQuery.fn.dataTable.tables().length > 0,
      null, {timeout: 10000});
  }
}

// One full round trip through a form: create a record in the UI, find it in
// the list, then open its edit page. This proves the CSRF token, the save
// action, the list's AJAX load, and the edit form. `fill` types the fields of
// the create form; `onEdit` runs extra checks on the edit page.
async function checkRoundTrip(page, {list, form, name, fill, onEdit}) {
  await page.goto(`${base}${list}/create`, {waitUntil: 'networkidle'});
  await fill();
  await Promise.all([page.waitForNavigation({waitUntil: 'networkidle'}), page.click(`#${form} button[type="submit"]`)]);
  await page.goto(base + list, {waitUntil: 'networkidle'});
  await page.locator('table tbody', {hasText: name}).waitFor({timeout: 10000});
  // The list's row link opens <list>/edit/<row id> (assets/fog/fog.common.js).
  const id = await page.evaluate((n) => {
    const row = jQuery.fn.dataTable.tables({api: true}).rows().data().toArray().find((r) => r.name === n);
    return row && row.id;
  }, name);
  if (!id) throw new Error(`no DataTables row has the name ${name}`);
  await checkPage(page, {path: `${list}/edit/${id}`});
  if (!(await page.locator(`input[value="${name}"]`).count())) throw new Error('the edit form does not show the saved name');
  if (onEdit) await onEdit();
}

// Each round trip returns the name it created, for the check files (ctx.created).
const checkStorageGroup = async (page) => {
  const name = `ui-smoke-${Date.now()}`;
  await checkRoundTrip(page, {
    list: '/storagegroups', form: 'storagegroup-create', name,
    fill: () => page.fill('#sgname', name)
  });
  return name;
};

// The host edit page is the only one with the MAC list and the Groups chip
// input (api/controllers/pages/edit.js), so it also drives both. It types a
// group name and does not save it, so it creates no Group.
const checkHost = async (page) => {
  const stamp = Date.now();
  const name = `uismoke${stamp}`;
  const mac = `02:00:${(stamp % 0xffffffff).toString(16).padStart(8, '0').match(/../g).join(':')}`;
  await checkRoundTrip(page, {
    list: '/hosts', form: 'host-create', name,
    fill: async () => {
      await page.fill('#hostname', name);
      // The create page has no tabs: the MAC field is in its own section card.
      await page.fill('input[name="macs[]"]', mac);
    },
    onEdit: async () => {
      await page.getByRole('tab', {name: 'MAC Addresses'}).click();
      const macRows = page.locator('input[name="macs[]"]');
      const before = await macRows.count();
      await page.click('.maclist-add');
      if (await macRows.count() !== before + 1) throw new Error('the MAC list "add" button did not add a row');
      // The browser must reject a bad MAC (the `pattern` attribute).
      await macRows.last().fill('not-a-mac');
      if (await macRows.last().evaluate((el) => el.checkValidity())) throw new Error('the MAC field accepted "not-a-mac"');
      await macRows.last().fill('');
      await page.getByRole('tab', {name: 'General'}).click();
      await page.fill('.fog-taginput-entry', 'ui-smoke-group');
      await page.press('.fog-taginput-entry', 'Enter');
      await page.locator('.fog-tag', {hasText: 'ui-smoke-group'}).waitFor({timeout: 5000});
    }
  });
  return name;
};

// Loads every check file in tools/smoke/checks/, in file-name order (see the
// comment at the top). A file without {name, run} stops the run here, before
// the lift.
const checksDir = path.join(__dirname, 'checks');
const CHECKS = fs.readdirSync(checksDir).filter((f) => f.endsWith('.js')).sort().map((f) => {
  const check = require(path.join(checksDir, f));
  if (typeof check.name !== 'string' || typeof check.run !== 'function') {
    throw new Error(`tools/smoke/checks/${f} must export {name, run}`);
  }
  return check;
});

async function main() {
  const target = await testDb.prepare();
  const datastores = {[target.datastore]: target.overrides};
  // Seed the Administrator into the test database, then close that Sails.
  // custom.testDatabase makes config/bootstrap.js refuse any other database.
  await new Promise((resolve, reject) => {
    schema.generate(password, 'admin@example.com', (err) => (err ? reject(err) : resolve()),
      {datastores, custom: {testDatabase: target.database}});
  });
  await new Promise((resolve) => require('sails').lower(() => resolve()));
  // The datastore overrides reach the server as sails_datastores__<name>__<key>.
  const datastoreEnv = {};
  for (const [key, value] of Object.entries(target.overrides)) {
    datastoreEnv[`sails_datastores__${target.datastore}__${key}`] = value;
  }
  // Production refuses to lift without socket origins. `npm run setup`
  // writes them, but `npm run setup:dev` does not, so the test sets the one
  // origin that its browser uses.
  const child = server.start({
    port, prod, log: serverLog,
    env: {
      'sails_sockets__onlyAllowOrigins': JSON.stringify([base]),
      'sails_custom__testDatabase': target.database,
      ...datastoreEnv
    }
  });
  // With custom.testDatabase set, config/bootstrap.js prints the database the
  // models use, and refuses to lift on another one. Keep that line, so the
  // check below does not depend on the 200 lines that serverLog keeps.
  let reported;
  let childOut = '';
  child.stdout.on('data', function watchDatabase(buf) {
    childOut += buf.toString();
    const match = /fog-node models database: (.+?)\r?\n/.exec(childOut);
    if (match) {
      reported = match[1];
      child.stdout.off('data', watchDatabase);
    } else {
      childOut = childOut.slice(-500);
    }
  });
  let browser;
  let failed = 0;
  const shot = async (page, label) => {
    fs.mkdirSync(outDir, {recursive: true});
    const file = path.join(outDir, `${label.replace(/[^a-z0-9]+/gi, '_')}.png`);
    try {
      await page.screenshot({path: file, fullPage: true});
      console.log(`    screenshot: ${file}`);
    } catch (e) {
      console.log(`    no screenshot: ${e.message.split('\n')[0]}`);
    }
  };
  const report = async (page, label, errors) => {
    if (!errors.length) return console.log(`ok    ${label}`);
    failed++;
    console.log(`FAIL  ${label}`);
    errors.slice(0, 10).forEach((e) => console.log(`    ${e.slice(0, 300)}`));
    await shot(page, label);
  };
  try {
    await server.waitForReady(child, base);
    // No browser action unless the server reported the test database.
    if (reported !== target.database) {
      throw new Error(`the server uses the database "${reported}", not the test database "${target.database}"`);
    }
    browser = await chromium.launch();
    const page = await browser.newPage();
    const loginErrors = await collectErrors(page, () => login(page));
    await report(page, 'login', loginErrors);
    // A script error on the login page still lets the pages be checked. Only a
    // login that did not happen stops the run.
    if (new URL(page.url()).pathname === '/login') throw new Error('cannot check the pages without a login');
    for (const spec of PAGES) {
      await report(page, spec.path, await collectErrors(page, () => checkPage(page, spec)));
    }
    const created = {};
    await report(page, 'create and edit a storage group', await collectErrors(page, async () => {
      created.storageGroup = await checkStorageGroup(page);
    }));
    await report(page, 'create and edit a host', await collectErrors(page, async () => {
      created.host = await checkHost(page);
    }));
    const ctx = {page, browser, base, checkPage, login, PAGES, created};
    for (const {name, run} of CHECKS) {
      await report(page, name, await collectErrors(page, () => run(ctx)));
    }
  } catch (e) {
    failed++;
    console.log(`FAIL  ${e.message}`);
  } finally {
    if (browser) await browser.close();
    server.stop(child);
  }
  if (failed) {
    console.log(`\n${failed} check(s) failed. Last fog-node output:\n${serverLog.slice(-40).join('\n')}`);
    process.exit(1);
  }
  console.log('\nAll UI checks passed.');
  // The seed's Sails app and its Redis client keep the process alive.
  process.exit(0);
}

main();
